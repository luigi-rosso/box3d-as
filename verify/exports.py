#!/usr/bin/env python3
# Checks that lib/box3d.as re-exports every name the public Box3D headers declare.
#   verify/exports.py          report exported, missing and unported names
#   verify/exports.py --write  regenerate lib/box3d.as from the names lib/ exports today
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
include = os.path.join(os.environ.get('BOX3D', os.path.expanduser('~/Projects/box3d')), 'include', 'box3d')
headers = ['base.h', 'id.h', 'constants.h', 'math_functions.h', 'collision.h', 'types.h', 'box3d.h']

# Compiler and platform plumbing with nothing to port.
plumbing = {
	'B3_API', 'B3_INLINE', 'B3_BREAKPOINT', 'B3_PRINTF_FORMAT', 'B3_ASSERT', 'B3_VALIDATE', 'B3_ENABLE_VALIDATION',
	'B3_DLL', 'B3_EXPORT', 'B3_IMPORT', 'B3_UNUSED', 'B3_ARRAY_COUNT', 'B3_ID_EQUALS', 'B3_IS_NULL', 'B3_IS_NON_NULL',
	'B3_CHECK_DEF', 'B3_LITERAL', 'B3_ZERO_INIT', 'B3_DEFAULT_CATEGORY_BITS_DEPRECATED', 'b3CreateWorldDoublePrecision',
	'BOX3D_DOUBLE_PRECISION', 'BOX3D_USER_CONFIG', 'BOX3D_EXPORT', 'B3_ALIGN_AS', 'B3_FORCE_INLINE', 'B3_NULL_ID',
	'B3_ID_INLINE', 'asNode',
}

# Skipped by design (CONVENTIONS): debug draw, recording and replay, file IO, and a declaration C never defines.
skipped = re.compile(
	r'^(b3_color\w+|b3HexColor|b3DebugMaterial|b3_debugMaterial\w+|b3MakeDebugColor|b3GetGraphColor|b3DefaultDebugDraw|'
	r'b3DebugShape|b3DebugDraw|b3World_Draw|b3Rec\w+|b3_recQuery\w+|b3Recording\w*|b3CreateRecording|b3DestroyRecording|'
	r'b3World_StartRecording|b3World_StopRecording|b3SaveRecordingToFile|b3LoadRecordingFromFile|b3ValidateReplay|'
	r'b3CreatePlayer|b3DestroyPlayer|b3DynamicTree_Save|b3DynamicTree_Load|b3DumpHeightData|b3LoadHeightField|'
	r'b3World_DumpShapeBounds)$'
)


def strip_comments(text):
	text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
	return re.sub(r'//[^\n]*', '', text)


def declared_names(path):
	text = strip_comments(open(path).read())
	names = []
	for m in re.finditer(r'^\s*#\s*define\s+([A-Za-z_]\w*)', text, re.M):
		names.append(m.group(1))
	body = re.sub(r'^\s*#.*$', '', text, flags=re.M)
	for m in re.finditer(r'\bB3_(?:API|INLINE|FORCE_INLINE|ID_INLINE)\b[^;{(]*?\b([A-Za-z_]\w*)\s*\(', body):
		names.append(m.group(1))
	for m in re.finditer(r'\btypedef\s+(?:struct|enum|union)\s*\w*\s*\{(.*?)\}\s*(\w+)\s*;', body, re.S):
		names.append(m.group(2))
		if re.search(r'\btypedef\s+enum', m.group(0)):
			for e in re.finditer(r'^\s*([A-Za-z_]\w*)\s*(?:=[^,\n]*)?,?\s*$', m.group(1), re.M):
				names.append(e.group(1))
	for m in re.finditer(r'\btypedef\s+[^;{}]*?\b(\w+)\s*\([^;]*\)\s*;', body):
		names.append(m.group(1))
	for m in re.finditer(r'\btypedef\s+(?:struct\s+)?\w+\s+(\w+)\s*;', body):
		names.append(m.group(1))
	for m in re.finditer(r'^(?:static\s+)?const\s+\w+\s+(\w+)\s*=', body, re.M):
		names.append(m.group(1))
	return names


def module_exports():
	exports = {}
	libdir = os.path.join(root, 'lib')
	for f in sorted(os.listdir(libdir)):
		if not f.endswith('.as') or f == 'box3d.as':
			continue
		module = f[:-3]
		text = open(os.path.join(libdir, f)).read()
		for m in re.finditer(r'^(?:@inline\s+)?export\s+(?:function|class|struct|const|let|type|enum)\s+([A-Za-z_]\w*)', text, re.M):
			exports.setdefault(m.group(1), []).append(module)
		for m in re.finditer(r'^export\s*\{([^}]*)\}\s*;', text, re.M):
			for part in m.group(1).split(','):
				part = part.strip()
				if part:
					exports.setdefault(part.split(' as ')[-1].strip(), []).append(module)
	return exports


def main():
	write = '--write' in sys.argv
	exports = module_exports()
	seen = set()
	byModule = {}
	missing = []
	for h in headers:
		for name in declared_names(os.path.join(include, h)):
			if name in seen or name in plumbing or skipped.match(name) or name.startswith('_'):
				continue
			seen.add(name)
			modules = exports.get(name)
			if modules and len(modules) > 1:
				print('warning: %s is defined in %s, exporting from %s' % (name, ', '.join(modules), modules[0]))
			if modules:
				byModule.setdefault(modules[0], []).append(name)
			else:
				missing.append((h, name))

	if write:
		out = [
			'// SPDX-FileCopyrightText: 2026 Erin Catto',
			'// SPDX-License-Identifier: MIT',
			'// AnimaScript port of include/box3d/box3d.h: the public API in one module.',
			'// Generated by verify/exports.py --write; regenerate after porting more of the API.',
			'',
		]
		for module in sorted(byModule):
			names = sorted(byModule[module])
			out.append('export {')
			out.extend('\t' + n + ',' for n in names)
			out.append('} from "./' + module + '";')
			out.append('')
		open(os.path.join(root, 'lib', 'box3d.as'), 'w').write('\n'.join(out))

	exported = sum(len(v) for v in byModule.values())
	print('exported %d names from %d modules' % (exported, len(byModule)))
	if missing:
		print('not exported yet, no module defines them: %d' % len(missing))
		for h, name in missing:
			print('  %-18s %s' % (h, name))
	return 0 if not missing else 1


sys.exit(main())
