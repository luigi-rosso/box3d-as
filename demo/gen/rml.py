"""A small DSL that emits RML with an explicit id on every element, so rive
never writes ids back into the generated file."""

from xml.sax.saxutils import quoteattr

_next_id = 1


def nid():
    global _next_id
    _next_id += 1
    return f"0:{_next_id}"


def _fmt(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        s = f"{v:.6f}".rstrip("0").rstrip(".")
        return s if s not in ("", "-0") else "0"
    if isinstance(v, (Node, VM)):
        return v.id
    return str(v)


class Node:
    def __init__(self, tag, attrs):
        self.tag = tag
        self.attrs = attrs
        self.kids = []
        self.meta = {}

    @property
    def id(self):
        return self.attrs["id"]

    def add(self, *kids):
        for k in kids:
            if isinstance(k, (list, tuple)):
                self.add(*k)
            elif k is not None:
                self.kids.append(k)
        return self

    def clone(self):
        """A deep copy with fresh ids, for subtrees holding no internal references."""
        copy = Node(self.tag, {**self.attrs, "id": nid()})
        return copy.add(*[k.clone() for k in self.kids])

    def write(self, out, depth):
        pad = "    " * depth
        attrs = " ".join(f"{k}={quoteattr(_fmt(v))}" for k, v in self.attrs.items() if v is not None)
        head = f"{pad}<{self.tag} {attrs}"
        if not self.kids:
            out.append(head + "/>")
            return
        out.append(head + ">")
        for k in self.kids:
            k.write(out, depth + 1)
        out.append(f"{pad}</{self.tag}>")


def E(element, /, *kids, **attrs):
    ident = attrs.pop("id", None) or nid()
    node = Node(element, {**attrs, "id": ident})
    return node.add(*kids)


def document(roots):
    out = ["<!-- Generated by demo/gen/shell.py; edit that and rerun it. -->", '<Rive version="1" kind="fragment">']
    for r in roots:
        r.write(out, 1)
    out.append("</Rive>")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- view models

_INSTANCE = {
    "Number": "ViewModelInstanceNumber",
    "String": "ViewModelInstanceString",
    "Boolean": "ViewModelInstanceBoolean",
    "Trigger": "ViewModelInstanceTrigger",
}


class VM:
    """A view model with one exported default instance."""

    def __init__(self, name):
        self.node = E("ViewModel", name=name)
        self.props = {}

    @property
    def id(self):
        return self.node.id

    def prop(self, kind, name, default=None):
        p = E(f"ViewModelProperty{kind}", name=name)
        p.meta["kind"] = kind
        p.meta["default"] = default
        self.node.add(p)
        self.props[name] = p
        return name

    def num(self, name, default=0.0):
        return self.prop("Number", name, float(default))

    def str(self, name, default=""):
        return self.prop("String", name, default)

    def bool(self, name, default=False):
        return self.prop("Boolean", name, default)

    def trig(self, name):
        return self.prop("Trigger", name)

    def instance(self):
        inst = E("ViewModelInstance", exports=True, name="Default")
        for p in self.props.values():
            kind = p.meta["kind"]
            value = None if kind == "Trigger" else p.meta["default"]
            inst.add(E(_INSTANCE[kind], propertyValue=value, viewModelPropertyId=p))
        self.node.add(inst)
        self.node.attrs = {"defaultInstanceId": inst.id, **self.node.attrs}
        return inst

    def path(self, name):
        return f"{self.id}-{self.props[name].id}"


# ------------------------------------------------------------------ binding

KEY = {"text": 268, "opacity": 18, "fractionalWidth": 706}
BINDABLE_KEY = {"Number": 636, "Boolean": 634, "Trigger": 686}


def bind(path, key, converter=None):
    return E("DataBindContext", sourcePathIds=path, propertyKey=KEY.get(key, key), converterId=converter)


def bindable(kind, path, value=None, write=False):
    ctx = E("DataBindContext", sourcePathIds=path, propertyKey=BINDABLE_KEY[kind], direction=True if write else None)
    return E(f"BindableProperty{kind}", ctx, propertyValue=value)


def set_vm(kind, path, value=None):
    """Listener action writing a literal, or firing a trigger."""
    return E("ListenerViewModelChange", bindable(kind, path, value, write=True))


def toggle_vm(path, negate):
    """Listener action flipping a boolean in place."""
    read_id = nid()
    return E(
        "ListenerViewModelChange",
        E(
            "BindablePropertyBoolean",
            E("DataBindContext", sourcePathIds=path, propertyKey=634, converterId=negate, id=read_id),
            E("DataBindContext", sourcePathIds=path, propertyKey=634, direction=True),
        ),
        fromViewModelProperty=True,
        fromDataBindId=read_id,
    )


def cond(kind, path, op, value):
    """Transition condition comparing a view model property to a literal."""
    literal = {"Boolean": "TransitionValueBooleanComparator", "Number": "TransitionValueNumberComparator"}[kind]
    return E(
        "TransitionViewModelCondition",
        E("TransitionPropertyViewModelComparator", bindable(kind, path)),
        E(literal, value=value),
        opValue=op,
    )


# -------------------------------------------------------- state machines


def key_anim(name, keys):
    """A one frame LinearAnimation holding {(object, property): value}; 8 hex
    digit strings key colors, ("uint", n) keys enums, numbers key doubles."""
    anim = E("LinearAnimation", name=name, duration=1)
    by_obj = {}
    for (obj, prop), value in keys.items():
        by_obj.setdefault(obj, []).append((prop, value))
    for obj, props in by_obj.items():
        ko = E("KeyedObject", objectId=obj)
        for prop, value in props:
            if isinstance(value, str):
                kf = E("KeyFrameColor", value=value, frame=0, interpolationType="linear")
            elif isinstance(value, tuple):
                kf = E("KeyFrameUint", value=value[1], frame=0, interpolationType="hold")
            else:
                kf = E("KeyFrameDouble", value=float(value), frame=0, interpolationType="linear")
            ko.add(E("KeyedProperty", kf, property=prop))
        anim.add(ko)
    return anim


class Machine:
    """Collects the layers, listeners and animations of one state machine."""

    def __init__(self, name):
        self.node = E("StateMachine", name=name)
        self.anims = []
        self.listeners = []
        self.layers = []

    def listen(self, target, kind, *actions):
        self.listeners.append(
            E(
                "StateMachineListenerSingle",
                *actions,
                targetId=target,
                listenerTypeValue=kind,
                name=f"{target.attrs['name']} {kind}",
            )
        )

    def layer(self, name, states):
        """states: [(name, keys, [(to index, duration ms, [conditions])])]; the
        first state is the entry."""
        y = 300 * len(self.layers)
        lay = E("StateMachineLayer", name=name)
        nodes = []
        for i, (state, keys, _) in enumerate(states):
            anim = key_anim(f"{name} {state}", keys)
            self.anims.append(anim)
            nodes.append(E("AnimationState", animationId=anim, x=200 + 220 * i, y=y))
        lay.add(
            E("AnyState", x=0, y=y - 120),
            E("ExitState", x=-200, y=y - 120),
            E("EntryState", E("StateTransition", stateToId=nodes[0]), x=0, y=y),
        )
        for node, (_, _, transitions) in zip(nodes, states):
            for to, ms, conds in transitions:
                node.add(E("StateTransition", *[c.clone() for c in conds], stateToId=nodes[to], duration=ms))
            lay.add(node)
        self.layers.append(lay)

    def build(self):
        self.node.add(*self.listeners, *self.layers)
        return self.node
